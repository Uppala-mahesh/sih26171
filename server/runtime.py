"""Authenticated, isolated runtime state for each installed extension.

The token is a bearer credential generated by the extension. It is never an
account ID: only its SHA-256 digest is retained as the in-memory lookup key.
"""
from __future__ import annotations

import contextlib
import hashlib
import re
import time
from dataclasses import dataclass, field
from typing import Dict, Iterator, Optional

from .browser_bridge import BrowserBridge, reset_current_bridge, set_current_bridge
from .events import EventBus, reset_current_bus, set_current_bus
from .loop import Registry, reset_current_registry, set_current_registry


TOKEN_RE = re.compile(r"^[A-Za-z0-9_-]{43,128}$")


class InvalidSessionToken(ValueError):
    pass


@dataclass
class SessionRuntime:
    key: str
    bus: EventBus = field(default_factory=EventBus)
    bridge: BrowserBridge = field(default_factory=BrowserBridge)
    registry: Registry = field(default_factory=Registry)
    last_seen: float = field(default_factory=time.monotonic)

    @contextlib.contextmanager
    def activate(self) -> Iterator["SessionRuntime"]:
        bus_token = set_current_bus(self.bus)
        bridge_token = set_current_bridge(self.bridge)
        registry_token = set_current_registry(self.registry)
        self.last_seen = time.monotonic()
        try:
            yield self
        finally:
            reset_current_registry(registry_token)
            reset_current_bridge(bridge_token)
            reset_current_bus(bus_token)


class RuntimeManager:
    def __init__(self) -> None:
        self._sessions: Dict[str, SessionRuntime] = {}
        # Keys of runtimes that a real extension has connected to, with the
        # moment it last did. See operator_runtime() for why this is tracked.
        self._agent_keys: Dict[str, float] = {}

    @staticmethod
    def token_key(token: str) -> str:
        if not TOKEN_RE.fullmatch(token or ""):
            raise InvalidSessionToken("missing or invalid session token")
        return hashlib.sha256(token.encode("utf-8")).hexdigest()

    def get(self, token: str) -> SessionRuntime:
        key = self.token_key(token)
        runtime = self._sessions.get(key)
        if runtime is None:
            runtime = SessionRuntime(key=key)
            self._sessions[key] = runtime
        runtime.last_seen = time.monotonic()
        return runtime

    def mark_agent_connected(self, key: str) -> None:
        """Record that a live extension owns this runtime."""
        self._agent_keys[key] = time.monotonic()

    def live_agent_runtime(self) -> Optional[SessionRuntime]:
        """The runtime of the most recently connected extension, if any."""
        if not self._agent_keys:
            return None
        key = max(self._agent_keys, key=lambda k: self._agent_keys[k])
        return self._sessions.get(key)

    def operator_runtime(self, token: str) -> SessionRuntime:
        """The runtime an operator UI should act inside.

        The cockpit is served over plain HTTP by this same process and cannot
        read the extension's storage, so it can never present the extension's
        own bearer token. Giving it a fresh runtime of its own looks like it
        works -- the socket opens, the bus flows -- but that runtime holds a
        different BrowserBridge, so every task it starts fails with "the
        browser extension is not connected" while the extension sits right
        there, connected, on someone else's runtime.

        So an operator UI joins the live extension's runtime instead. This is a
        local, single-operator tool bound to 127.0.0.1 driving one Chrome
        profile; when more than one extension is connected, the most recently
        connected one is the one the operator is looking at.
        """
        live = self.live_agent_runtime()
        if live is not None:
            live.last_seen = time.monotonic()
            return live
        return self.get(token)

    @property
    def session_count(self) -> int:
        return len(self._sessions)


runtimes = RuntimeManager()
