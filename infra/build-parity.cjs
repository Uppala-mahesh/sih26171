/**
 * Build the cross-runtime parity harness.
 *
 * Two steps, in order:
 *   1. Compile the TypeScript sources under packages/ to dist/ as CommonJS.
 *   2. Write dist/package.json declaring CommonJS.
 *
 * Step 2 exists because the root package.json declares `"type": "module"`,
 * which makes Node treat every `.js` file below it as ESM. The parity build
 * emits CommonJS, so without this marker Node refuses to load it:
 *
 *     ReferenceError: exports is not defined in ES module scope
 *
 * The marker is scoped to dist/ only. The extension and console builds are
 * genuinely ESM and are unaffected.
 */

'use strict';

const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const DIST = path.join(ROOT, 'dist');

const tsc = path.join(ROOT, 'node_modules', '.bin', process.platform === 'win32' ? 'tsc.cmd' : 'tsc');

console.log('> compiling packages/ to dist/ (CommonJS)');
const build = spawnSync(tsc, ['-p', 'tsconfig.build.json'], {
  cwd: ROOT,
  stdio: 'inherit',
  shell: process.platform === 'win32',
});

if (build.status !== 0) {
  console.error('build failed');
  process.exit(build.status ?? 1);
}

fs.mkdirSync(DIST, { recursive: true });
fs.writeFileSync(
  path.join(DIST, 'package.json'),
  `${JSON.stringify(
    {
      type: 'commonjs',
      _comment:
        'Generated by infra/build-parity.cjs. Scopes CommonJS to the parity build output only.',
    },
    null,
    2,
  )}\n`,
  'utf8',
);

console.log('> wrote dist/package.json (type: commonjs)');
console.log('build ok');
